                return null;

            while (result.EndsWith("_")) // Remove this for duplicate monsters
                result = result.Remove(result.Length - 1);

            result = result.Replace("_", " ");

            return result;
        }

        public static bool Exists(int key)
        {
            string result = null;
            result = Enum.GetName(typeof(AggressiveMonstersEnum), key);

            if (result == null)
