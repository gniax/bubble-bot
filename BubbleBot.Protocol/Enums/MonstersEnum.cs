    public static class MonstersEnumFinder
    {
        public static string GetMonsterNameById(int key)
        {
            string result = null;
            result = Enum.GetName(typeof(MonstersEnum), key);
            if (result == null)
                return null;

            while (result.EndsWith("_")) // Remove this for duplicate monsters
                result = result.Remove(result.Length - 1);

            result = result.Replace("_", " ");

            return result;
        }
    }
